/** Resolve a service icon name from site data. */
export function ServiceIcon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  switch (name) {
    case 'truck':
      return <TruckIcon className={className} />;
    case 'ruler':
      return <RulerIcon className={className} />;
    case 'wrench':
      return <WrenchIcon className={className} />;
    case 'shield':
      return <ShieldIcon className={className} />;
    default:
      return <SparkleIcon className={className} />;
  }
}
